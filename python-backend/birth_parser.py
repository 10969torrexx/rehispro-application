def remove_similar_sentences(source_list, reference_list, threshold=70):
    cleaned = []
    junk_pattern = re.compile(r"^(?=.*[A-Za-z])(?=.*\d)[A-Za-z\d]{1,5}$")  
    numbered_dot_pattern = re.compile(r"^\d+\.$")
    noisy_symbol_pattern = re.compile(r"[^\w\s.'-]")

    for src in source_list:
        s = src.strip()

        if " " in s:
            parts = s.split()
            first_word = parts[0].lower().rstrip(":")
            if "/" in first_word or first_word in reference_list:
                # only keep the part after the label
                old_value = s
                s = " ".join(parts[1:])
                logger.info(f"[DEBUG] Split merged OCR text: '{old_value}' → '{s}'")

        if "(" in s or ")" in s:
            continue

        if junk_pattern.match(s):
            continue

        if len(s) < 2 or re.fullmatch(r"[^A-Za-z0-9]+", s):
            continue

        if noisy_symbol_pattern.search(s):
            continue
        
        if numbered_dot_pattern.match(s):
            continue

        match = process.extractOne(s, reference_list, scorer=fuzz.token_set_ratio)
        if match:
            _, score, _ = match
            if score >= threshold:
                continue
        cleaned.append(s)

    return cleaned

MONTHS = [
    "JANUARY", "FEBRUARY", "MARCH", "APRIL", "MAY", "JUNE",
    "JULY", "AUGUST", "SEPTEMBER", "OCTOBER", "NOVEMBER", "DECEMBER"
]

def merge_split_dates(ocr_list):
    merged = []
    skip_next = False
    for i in range(len(ocr_list)):
        if skip_next:
            skip_next = False
            continue

        current = ocr_list[i].strip()
        next_item = ocr_list[i + 1].strip() if i + 1 < len(ocr_list) else ""

        parts = current.split()
        if (
            len(parts) >= 2
            and parts[0] in MONTHS
            and re.match(r"^\d{1,2},$", parts[1])
            and re.match(r"^\d{4}$", next_item)
        ):
            merged.append(f"{current} {next_item}")
            skip_next = True
        else:
            merged.append(current)

    return merged

def fill_template_from_list(template: dict, ocr_list: list):
    """
    TODO: Dynamically fills a template dictionary with values from an OCR result list.

    - Assigns OCR text in order to template keys.
    - If there are fewer OCR entries than keys, remaining keys stay empty.
    - If there are more OCR entries, extras are ignored.
    - Depending of certain keys it will check if value is valid for the key; skips if otherwise

    Returns: a new filled dictionary (does not modify original).
    """

    filled = template.copy()
    keys = list(filled.keys())

    numeric_keys = ["children_born_alive", "children_still_living", "children_deceased"]
    notvalid_values = {
        "attendant_others_specify": "dale",
    }
    valid_values = {
        "sex": ["MALE", "FEMALE", "OTHER"]
    }
    ocr_index = 0
    key_index = 0
    while key_index < len(keys) and ocr_index < len(ocr_list):
        key = keys[key_index]
        value = ocr_list[ocr_index].strip() if isinstance(ocr_list[ocr_index], str) else ocr_list[ocr_index]
        if key in numeric_keys:
            try:
                int(value)
                filled[key] = value
                key_index += 1
                ocr_index += 1
            except (ValueError, TypeError):
                filled[key] = ""
                key_index += 1
        elif key in notvalid_values and str(value).lower() == str(notvalid_values[key]).lower():
            filled[key] = ""
            key_index += 1
            ocr_index += 1
        elif key in valid_values and value not in valid_values[key]:
            filled[key] = ""
            key_index += 1
            ocr_index += 1
        else:
            filled[key] = value
            key_index += 1
            ocr_index += 1

    return filled


def parse(ocr_text):
    cleaned = remove_similar_sentences(ocr_text, default_keywords, threshold=80)
    cleaned = merge_split_dates(cleaned)
    template_form = fill_template_from_list(template, cleaned)
    return template_form